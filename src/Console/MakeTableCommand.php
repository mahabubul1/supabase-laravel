<?php

declare(strict_types=1);

namespace BlackDevs\SupabaseLaravel\Console;

use Illuminate\Console\Command;
use Illuminate\Support\Str;

/**
 * Scaffolds a timestamped .sql migration file (Laravel migration naming
 * convention) to be run through `supabase:migrate`. Each file holds an
 * `-- up` section applied by `supabase:migrate` and a matching `-- down`
 * section applied by `supabase:rollback-table` — this is NOT a Laravel
 * migration, since it targets Supabase's Postgres instance directly rather
 * than this app's local database connection.
 */
class MakeTableCommand extends Command
{
    protected $signature = 'supabase:make-table {name : Migration name, e.g. create_customers_table or add_paid_to_invoices_table}
        {--path= : Directory to write the .sql file into (default: database/supabase/tables)}';

    protected $description = 'Scaffold a timestamped .sql migration file to run through supabase:migrate';

    public function handle(): int
    {
        $name = Str::snake((string) $this->argument('name'));
        $directory = rtrim((string) ($this->option('path') ?: base_path('database/supabase/tables')), '/');
        $path = "{$directory}/".now()->format('Y_m_d_His')."_{$name}.sql";

        if (! is_dir($directory) && ! mkdir($directory, 0755, true) && ! is_dir($directory)) {
            $this->components->error("Could not create directory {$directory}.");

            return self::FAILURE;
        }

        file_put_contents($path, $this->stub($name));

        $this->components->info("Created {$path}");
        $this->components->warn(
            'This file is not run automatically — apply pending migrations with `php artisan supabase:migrate`.',
        );

        return self::SUCCESS;
    }

    protected function stub(string $name): string
    {
        if (preg_match('/^create_(.+)_table$/', $name, $matches) === 1) {
            $table = $matches[1];

            return <<<SQL
-- Migration: {$name}
--
-- Apply with:  php artisan supabase:migrate
-- Rollback with: php artisan supabase:rollback-table

-- up
create table if not exists public.{$table} (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now()
);

grant select, insert, update, delete on public.{$table} to anon, authenticated, service_role;

-- down
drop table if exists public.{$table};

SQL;
        }

        if (preg_match('/^add_(.+)_to_(.+)_table$/', $name, $matches) === 1) {
            $column = $matches[1];
            $table = $matches[2];

            return <<<SQL
-- Migration: {$name}
--
-- Apply with:  php artisan supabase:migrate
-- Rollback with: php artisan supabase:rollback-table

-- up
alter table public.{$table} add column {$column} text; -- TODO: adjust the type/default/constraints

-- down
alter table public.{$table} drop column {$column};

SQL;
        }

        return <<<SQL
-- Migration: {$name}
--
-- Apply with:  php artisan supabase:migrate
-- Rollback with: php artisan supabase:rollback-table

-- up
-- TODO: write the migration SQL

-- down
-- TODO: write the SQL that reverses the "up" section above

SQL;
    }
}
